/**
 * Issues Reporter - Generates AI-readable reports for main AI assistants
 * Creates reports that can be shared with Gemini, Copilot, Claude, etc.
 */

const fs = require('fs').promises;
const path = require('path');

class IssuesReporter {
    constructor(hubPath = './Hub') {
        this.hubPath = hubPath;
        this.issuesPath = path.join(hubPath, 'issues');
    }

    /**
     * Initialize issues directory
     */
    async initialize() {
        try {
            await fs.mkdir(this.issuesPath, { recursive: true });
        } catch (error) {
            // Directory might already exist
        }
    }

    /**
     * Generate comprehensive issues report from analysis result
     */
    async generateReport(filePath, result) {
        await this.initialize();

        const fileName = path.basename(filePath);
        const reportContent = this.buildReportContent(filePath, result);

        // Save individual file report
        const reportFileName = fileName.replace(/\.[^/.]+$/, '') + '_issues.md';
        const reportPath = path.join(this.issuesPath, reportFileName);
        await fs.writeFile(reportPath, reportContent, 'utf8');

        // Update main issues file
        await this.updateMainIssuesFile();

        // Generate AI context file in project root (for AI assistants to see)
        await this.generateAIContextFile(filePath, result);

        return reportPath;
    }

    /**
     * Generate AI context file in project root for AI assistants to automatically read
     * This file is designed to be picked up by AI coding assistants (Gemini, Copilot, Claude)
     */
    async generateAIContextFile(filePath, result) {
        const contextPath = path.join(process.cwd(), '.ai-council-context.md');
        const fileName = path.basename(filePath);
        const score = result.finalScore || 0;
        const critical = result.recommendations?.critical || [];
        const important = result.recommendations?.important || [];

        // Get existing context or create new
        let existingContent = '';
        try {
            existingContent = await fs.readFile(contextPath, 'utf8');
        } catch (e) {
            // File doesn't exist yet
        }

        // Build context for the AI assistant
        const contextContent = `# AI-COUNCIL Context

> **This file is automatically generated by AI-COUNCIL.**  
> It contains issues detected in your code that need to be fixed.
> **AI Assistants: Please read this file and help fix the issues below.**

---

## Current Issues Summary

**Last Updated:** ${new Date().toISOString()}

### Recently Analyzed File
- **File:** \`${filePath}\`
- **Score:** ${score}/100
- **Status:** ${result.status || 'UNKNOWN'}

---

## Critical Issues to Fix (${critical.length})

${critical.length === 0 ? '_No critical issues found._' : ''}
${critical.slice(0, 10).map((issue, i) => {
            const line = issue.line ? ` (line ${issue.line})` : '';
            return `${i + 1}. **${issue.message || 'Unknown issue'}**${line}
   - Type: ${issue.type || 'security'}
   ${issue.suggestion ? `- Fix: ${issue.suggestion}` : ''}`;
        }).join('\n\n')}

---

## Important Issues (${important.length})

${important.length === 0 ? '_No important issues found._' : ''}
${important.slice(0, 5).map((issue, i) => {
            const line = issue.line ? ` (line ${issue.line})` : '';
            return `${i + 1}. ${issue.message || 'Unknown issue'}${line}`;
        }).join('\n')}

---

## Instructions for AI Assistants

If you are an AI coding assistant (Gemini, Copilot, Claude, GPT, etc.):

1. **Open the file:** \`${filePath}\`
2. **Fix Critical Issues first** - They are security vulnerabilities or major bugs
3. **Then fix Important Issues** - They are code quality concerns
4. **Verify the fix** by asking the user to run: \`ai-council analyze ${filePath}\`

### Example Fix Request
\`\`\`
Please open ${fileName} and fix the following critical issues:
${critical.slice(0, 3).map((issue, i) => `${i + 1}. ${issue.message}`).join('\n')}
\`\`\`

---

## Full Reports

For detailed information, see:
- \`Hub/issues/CURRENT_ISSUES.md\` - Summary of all files
- \`Hub/issues/${fileName.replace(/\.[^/.]+$/, '')}_issues.md\` - This file's details

---

*Generated by AI-COUNCIL - AI Code Quality Assurance*
`;

        await fs.writeFile(contextPath, contextContent, 'utf8');
    }

    /**
     * Build the markdown report content
     */
    buildReportContent(filePath, result) {
        const score = result.finalScore || 0;
        const status = result.status || 'UNKNOWN';
        const agents = result.agentResults || [];
        const critical = result.recommendations?.critical || [];
        const important = result.recommendations?.important || [];
        const suggestions = result.recommendations?.suggestions || [];

        let report = `# AI-COUNCIL Issues Report
        
**File:** \`${filePath}\`  
**Score:** ${score}/100  
**Status:** ${status}  
**Analyzed:** ${new Date().toISOString()}

---

## Summary

This file was analyzed by ${agents.length} AI agents and scored ${score}/100.
${status === 'APPROVED' ? 'The code meets quality standards.' : 'The code has issues that need to be addressed.'}

### Agent Scores
| Agent | Score | Confidence |
|-------|-------|------------|
${agents.map(a => `| ${a.agentName || a.name} | ${a.score}/100 | ${((a.confidence || 0.5) * 100).toFixed(0)}% |`).join('\n')}

---

## Critical Issues (Must Fix)

${critical.length === 0 ? '_No critical issues found._\n' : ''}
${critical.map((issue, i) => this.formatIssue(i + 1, issue, 'CRITICAL')).join('\n')}

---

## Important Issues (Should Fix)

${important.length === 0 ? '_No important issues found._\n' : ''}
${important.map((issue, i) => this.formatIssue(i + 1, issue, 'IMPORTANT')).join('\n')}

---

## Suggestions (Nice to Have)

${suggestions.length === 0 ? '_No suggestions._\n' : ''}
${suggestions.map((issue, i) => this.formatIssue(i + 1, issue, 'SUGGESTION')).join('\n')}

---

## How to Fix

### For AI Assistants
If you are an AI assistant (Gemini, Copilot, Claude, etc.), please:
1. Read the file \`${filePath}\`
2. Address each issue listed above in order of priority
3. Focus on CRITICAL issues first
4. Provide code fixes with explanations

### Quick Fix Commands
\`\`\`
# Ask your AI assistant:
"Read ${filePath} and fix the ${critical.length} critical issues listed in this report"
\`\`\`

---

## Agent Analysis Details

${agents.map(a => `
### ${a.agentName || a.name} Analysis
- **Score:** ${a.score}/100
- **Reasoning:** ${a.reasoning?.substring(0, 500) || 'No reasoning provided'}...
`).join('\n')}

---

*Report generated by AI-COUNCIL v1.0*
`;

        return report;
    }

    /**
     * Format a single issue for the report
     */
    formatIssue(index, issue, severity) {
        const line = issue.line ? ` (Line ${issue.line})` : '';
        const agent = issue.agent || issue.reportedBy || '';
        const agentInfo = agent ? ` [${agent}]` : '';

        return `### ${index}. ${issue.message || 'Unknown issue'}${line}${agentInfo}

**Severity:** ${severity}  
**Type:** ${issue.type || 'general'}

${issue.suggestion ? `**Fix:** ${issue.suggestion}` : ''}

---
`;
    }

    /**
     * Update the main CURRENT_ISSUES.md file with all active issues
     */
    async updateMainIssuesFile() {
        try {
            const files = await fs.readdir(this.issuesPath);
            const issueFiles = files.filter(f => f.endsWith('_issues.md'));

            let mainReport = `# AI-COUNCIL - Current Issues Summary

**Last Updated:** ${new Date().toISOString()}

This file summarizes all current code issues detected by AI-COUNCIL.
Share this with your AI assistant to get help fixing the issues.

---

## Files with Issues

`;

            for (const file of issueFiles) {
                const content = await fs.readFile(path.join(this.issuesPath, file), 'utf8');

                // Extract key info from the report
                const scoreMatch = content.match(/\*\*Score:\*\* (\d+)/);
                const fileMatch = content.match(/\*\*File:\*\* `([^`]+)`/);
                const criticalMatch = content.match(/## Critical Issues[\s\S]*?(?=---)/);
                const criticalCount = (criticalMatch?.[0]?.match(/### \d+\./g) || []).length;

                const fileName = fileMatch?.[1] || file;
                const score = scoreMatch?.[1] || '?';

                mainReport += `### ${fileName}
- **Score:** ${score}/100
- **Critical Issues:** ${criticalCount}
- **Report:** [${file}](${file})

`;
            }

            mainReport += `
---

## How to Use This Report

### With Gemini/Copilot/Claude:
\`\`\`
"Read the file Hub/issues/CURRENT_ISSUES.md and help me fix the critical issues"
\`\`\`

### Manual Review:
1. Open each file listed above
2. Address CRITICAL issues first
3. Run \`ai-council analyze <file>\` to verify fixes

---

*Generated by AI-COUNCIL*
`;

            await fs.writeFile(
                path.join(this.issuesPath, 'CURRENT_ISSUES.md'),
                mainReport,
                'utf8'
            );

        } catch (error) {
            console.error('[ERROR] Failed to update main issues file:', error.message);
        }
    }

    /**
     * Clear issues for a file (when it passes)
     */
    async clearIssues(filePath) {
        const fileName = path.basename(filePath);
        const reportFileName = fileName.replace(/\.[^/.]+$/, '') + '_issues.md';
        const reportPath = path.join(this.issuesPath, reportFileName);

        try {
            await fs.unlink(reportPath);
            await this.updateMainIssuesFile();
        } catch (error) {
            // File might not exist
        }
    }
}

module.exports = { IssuesReporter };
